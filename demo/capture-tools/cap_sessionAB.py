"""Session AB (desktop 1920x1080): studio correction, guide regen, review, approve."""
import asyncio, re, time
from playwright.async_api import async_playwright

OUT = "C:/Users/dougl/Documents/MetaHackaton/demo/assets/captures"
T0 = time.time()
def mark(n):
    print(f"MARK {n} t={time.time()-T0:.1f}", flush=True)

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(channel="chrome", args=["--no-sandbox"])
        ctx = await b.new_context(viewport={"width":1920,"height":1080},
            record_video_dir=OUT, record_video_size={"width":1920,"height":1080})
        pg = await ctx.new_page()
        await pg.goto("http://localhost:5173", wait_until="networkidle")
        await pg.wait_for_timeout(1200)
        await pg.get_by_role("button", name="Tutorials").first.click()
        await pg.wait_for_timeout(1200)
        await pg.get_by_text("Adjustment-knob check").first.wait_for(timeout=30000)
        await pg.get_by_text("Adjustment-knob check").first.scroll_into_view_if_needed()
        await pg.wait_for_timeout(500)
        await pg.get_by_text("Adjustment-knob check").first.click()
        await pg.wait_for_timeout(2000)
        mark("studio-open")
        await pg.locator(".avatar-btn").click()
        await pg.wait_for_timeout(800)
        await pg.locator("#demo-role").select_option("expert")
        await pg.wait_for_timeout(1000)
        mark("role-expert")
        await pg.get_by_role("button", name="Tutorials").first.click()
        await pg.wait_for_timeout(1200)
        await pg.get_by_text("Adjustment-knob check").first.wait_for(timeout=30000)
        await pg.get_by_text("Adjustment-knob check").first.scroll_into_view_if_needed()
        await pg.wait_for_timeout(500)
        await pg.get_by_text("Adjustment-knob check").first.click()
        await pg.wait_for_timeout(2000)
        mark("studio-open-2")
        try:
            await pg.get_by_role("button", name="Dismiss").click(timeout=4000)
        except Exception:
            pass
        await pg.wait_for_timeout(1500)
        await pg.evaluate("window.scrollTo(0, 900)")
        await pg.wait_for_timeout(1000)
        mark("overview-provenance")
        await pg.screenshot(path=f"{OUT}/ab-overview.png")
        await pg.wait_for_timeout(6000)
        await pg.evaluate("window.scrollTo(0,0)")
        await pg.locator("button", has_text="Content").first.click(timeout=8000)
        await pg.wait_for_timeout(1500)
        mark("content-open")
        await pg.locator('input[placeholder^="e.g. Power"]').nth(0).fill("Locate the adjustment knob")
        await pg.locator('textarea[placeholder^="Imperative"]').nth(0).fill("Find the amber-ringed adjustment knob on the right side of the trainer panel.")
        await pg.locator('input[placeholder^="What the technician"]').nth(0).fill("Knob identified; pointer visible against the scale.")
        mark("step1-fixed")
        await pg.wait_for_timeout(2000)
        await pg.evaluate("var items=[...document.querySelectorAll('button')].filter(b=>/Observed activity segment 2/.test(b.textContent)); if(items[0]) items[0].click()")
        await pg.wait_for_timeout(1500)
        await pg.locator('input[placeholder^="e.g. Power"]').nth(0).fill("Check and align the indicator")
        await pg.locator('textarea[placeholder^="Imperative"]').nth(0).fill("Read the indicator position, then turn the knob until the needle lines up with the center mark.")
        await pg.locator('input[placeholder^="What the technician"]').nth(0).fill("Needle centered on the mark.")
        mark("step2-fixed")
        await pg.wait_for_timeout(2000)
        await pg.screenshot(path=f"{OUT}/ab-steps-fixed.png")
        await pg.get_by_role("button", name="Save steps").click()
        await pg.wait_for_timeout(3000)
        mark("steps-saved")
        await pg.screenshot(path=f"{OUT}/ab-steps-saved.png")
        await pg.evaluate("window.scrollTo(0,0)")
        await pg.locator("button", has_text="Guide").first.click(timeout=8000)
        await pg.wait_for_timeout(1500)
        await pg.get_by_role("button", name="Change format").click()
        await pg.wait_for_timeout(1500)
        await pg.locator('[role="radio"]', has_text="Illustrated Work Instruction").click()
        mark("format-selected")
        await pg.wait_for_timeout(1500)
        await pg.get_by_role("button", name="Generate new version").click()
        await pg.wait_for_timeout(4000)
        mark("guide-generated")
        await pg.screenshot(path=f"{OUT}/ab-guide-new.png")
        await pg.get_by_role("button", name="Regenerate guide").click()
        await pg.wait_for_timeout(4000)
        mark("guide-regenerated")
        await pg.evaluate("window.scrollTo(0, 900)")
        await pg.wait_for_timeout(1000)
        await pg.screenshot(path=f"{OUT}/ab-guide-final.png")
        await pg.wait_for_timeout(5000)
        await pg.evaluate("window.scrollTo(0,0)")
        await pg.get_by_role("button", name="Open in Review").click()
        await pg.wait_for_timeout(2500)
        mark("review-draft")
        await pg.screenshot(path=f"{OUT}/ab-review-draft.png")
        await pg.wait_for_timeout(5000)
        try:
            await pg.get_by_role("button", name="Submit for review").click(timeout=5000)
            await pg.wait_for_timeout(2500)
            mark("submitted")
        except Exception:
            mark("already-submitted")
            print("Submit button absent; continuing", flush=True)
        await pg.screenshot(path=f"{OUT}/ab-submitted.png")
        await pg.locator(".avatar-btn").click()
        await pg.wait_for_timeout(800)
        await pg.locator("#demo-role").select_option("reviewer")
        await pg.wait_for_timeout(1500)
        mark("role-reviewer")
        await pg.get_by_role("button", name=re.compile(r"^Review")).first.click()
        await pg.wait_for_timeout(2000)
        try:
            await pg.get_by_role("button", name="Pending review").click(timeout=6000)
            await pg.wait_for_timeout(1500)
        except Exception:
            pass
        await pg.screenshot(path=f"{OUT}/ab-review-queue.png")
        await pg.evaluate("var bs=[...document.querySelectorAll('button')].filter(b=>/Adjustment-knob check/.test(b.textContent)); if(bs[0]) bs[0].click()")
        await pg.wait_for_timeout(2000)
        await pg.screenshot(path=f"{OUT}/ab-review-open.png")
        await pg.get_by_role("button", name="Approve").click()
        await pg.wait_for_timeout(1500)
        await pg.screenshot(path=f"{OUT}/ab-approve-confirm.png")
        await pg.get_by_role("button", name="Yes, approve").click()
        await pg.wait_for_timeout(3000)
        mark("approved-v1")
        await pg.screenshot(path=f"{OUT}/ab-approved.png")
        await pg.wait_for_timeout(6000)
        await pg.get_by_role("button", name="Procedures").first.click()
        await pg.wait_for_timeout(2000)
        mark("procedures")
        await pg.screenshot(path=f"{OUT}/ab-procedures.png")
        await pg.wait_for_timeout(6000)
        await ctx.close(); await b.close()

asyncio.run(main())
